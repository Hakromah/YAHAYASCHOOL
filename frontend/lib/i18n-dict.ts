/**
 * Translate a key string dynamically based on locale with fallback to English.
 */
export function t(key: string | undefined | null, locale: string = 'en'): string {
  if (!key) return '';
  const loc = (locale || 'en').toLowerCase();
  if (loc === 'en') return key;

  const langDict = i18nDict[loc as 'ar' | 'fr' | 'tr'];
  if (!langDict) return key;

  const normalizedKey = key.trim().toLowerCase().replace(/\s+/g, ' ');
  return langDict[normalizedKey] || langDict[normalizedKey.replace(/\.$/, '')] || key;
}

export default t;
